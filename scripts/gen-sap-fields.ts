// Reads Amber's SAP field dictionary (docs/SAP_Fields_Amber.xlsx) and writes src/data/sap/sapFields.ts.
// Run once with `npm run gen:sap` and commit the output. The app never parses the xlsx at runtime.
import XLSX from 'xlsx'
import fs from 'node:fs'
import path from 'node:path'

type Status = 'confirmed' | 'to_confirm' | 'calculated'
interface Row {
  code: string
  report: string
  label: string
  tableField: string
  dataType: string
  valueKind: string
  description: string
  detail: string
  status: Status
}

const root = path.resolve(import.meta.dirname, '..')
const wb = XLSX.readFile(path.join(root, 'docs/SAP_Fields_Amber.xlsx'))

const REPORTS: Record<string, string> = {
  'Material Master': 'Material Master',
  'Inventory ': 'Inventory (MB52)',
  Inventory: 'Inventory (MB52)',
  GRN: 'GRN',
  PO: 'Purchase Order (ME2N)',
  PR: 'Purchase Requisition (ME5A)',
  'FA Code': 'FA Code',
  Expense: 'Import expense conditions',
}

const STRICT = /^[A-Z0-9_/]+-[A-Z0-9_]+$/
const clean = (v: unknown) => String(v ?? '').replace(/\s+/g, ' ').trim()

function statusOf(tf: string): Status {
  const t = tf.toLowerCase()
  if (t.startsWith('calculated')) return 'calculated'
  if (t.includes('confirm') || t.includes('custom') || t.includes('report field') || t.includes('report flag') || t.includes('classification')) return 'to_confirm'
  return STRICT.test(tf) ? 'confirmed' : 'to_confirm'
}

const out: Row[] = []
const seen = new Set<string>()

for (const sheetName of wb.SheetNames) {
  // The "Vendor Master" sheet Amber sent is a duplicate of the PO sheet; skip it (see Appendix A).
  if (sheetName.trim() === 'Vendor Master') continue
  const report = REPORTS[sheetName] ?? sheetName.trim()
  const rows = XLSX.utils.sheet_to_json<unknown[]>(wb.Sheets[sheetName], { header: 1, blankrows: false })
  for (const r of rows.slice(2)) {
    if (!r || !r[1]) continue
    const isExpense = report === 'Import expense conditions'
    const label = clean(r[1])
    const tableField = clean(r[6])
    let code: string
    if (isExpense) code = `COND-${clean(r[0])}`
    else if (STRICT.test(tableField)) code = tableField
    else code = `${report}:${label}`
    const key = `${report}|${code}`
    if (seen.has(key)) continue
    seen.add(key)
    out.push({
      code,
      report,
      label,
      tableField: isExpense ? `${tableField} [${clean(r[0])}]` : tableField,
      dataType: clean(r[5]),
      valueKind: clean(r[4]),
      description: clean(r[2]),
      detail: clean(r[3]),
      status: isExpense ? 'confirmed' : statusOf(tableField),
    })
  }
}

// Standard vendor-master fields: Amber's Vendor Master sheet was a duplicate of the PO sheet,
// so these come from standard SAP and stay "to confirm with Amber IT".
const vendorStd: [string, string, string, string][] = [
  ['LFA1-LIFNR', 'Vendor', 'CHAR 10', 'Vendor account number.'],
  ['LFA1-NAME1', 'Name of Supplier', 'CHAR 35', 'Vendor name.'],
  ['LFA1-LAND1', 'Country', 'CHAR 3', 'Country key of the vendor.'],
  ['LFA1-STCD3', 'GSTIN', 'CHAR 18', 'Tax number 3, used for GSTIN in India.'],
  ['LFA1-SPERM', 'Purchasing block', 'CHAR 1', 'Central purchasing block for the vendor.'],
  ['LFB1-ZTERM', 'Payment terms', 'CHAR 4', 'Terms of payment key (company code level).'],
  ['LFM1-EKORG', 'Purch. Organization', 'CHAR 4', 'Purchasing organisation data for the vendor.'],
]
for (const [code, label, dataType, description] of vendorStd) {
  out.push({ code, report: 'Vendor Master (standard SAP)', label, tableField: code, dataType, valueKind: 'Alphanumeric', description, detail: description, status: 'to_confirm' })
}
// Standard GRN-adjacent table not in the sheet but needed for delay days.
out.push({ code: 'RBKP-BELNR', report: 'GRN', label: 'IR. Doc', tableField: 'RBKP-BELNR', dataType: 'CHAR 10', valueKind: 'Alphanumeric', description: 'Invoice receipt document number.', detail: 'Invoice document posted in logistics invoice verification (MIRO).', status: 'to_confirm' })

const dir = path.join(root, 'src/data/sap')
fs.mkdirSync(dir, { recursive: true })
const header = `// GENERATED by scripts/gen-sap-fields.ts from docs/SAP_Fields_Amber.xlsx. Do not edit by hand.\n// ${out.length} fields.\n`
const body = `import type { SapFieldDef } from '../types'\n\nexport const SAP_FIELDS: SapFieldDef[] = ${JSON.stringify(out, null, 1)}\n`
fs.writeFileSync(path.join(dir, 'sapFields.ts'), header + body)
const byReport = out.reduce<Record<string, number>>((a, r) => ((a[r.report] = (a[r.report] ?? 0) + 1), a), {})
console.log(`Wrote ${out.length} SAP fields`, byReport)
